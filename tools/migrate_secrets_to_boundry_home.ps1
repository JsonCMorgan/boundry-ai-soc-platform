# Copy C:\Dev\MSSP\.env to %USERPROFILE%\.boundry\secrets.env (merge, no stdout secrets).
# Run once after hardening; then trim MSSP\.env to non-secrets only or delete keys from repo copy.
$ErrorActionPreference = 'Stop'
$src = 'C:\Dev\MSSP\.env'
$destDir = Join-Path $env:USERPROFILE '.boundry'
$dest = Join-Path $destDir 'secrets.env'

if (-not (Test-Path $src)) {
    Write-Host 'No C:\Dev\MSSP\.env — nothing to migrate.'
    exit 0
}

if (-not (Test-Path $destDir)) { New-Item -ItemType Directory -Path $destDir -Force | Out-Null }

$existing = @{}
if (Test-Path $dest) {
    Get-Content $dest -Encoding UTF8 | ForEach-Object {
        if ($_ -match '^\s*#' -or $_ -match '^\s*$') { return }
        if ($_ -match '^([^=]+)=(.*)$') { $existing[$matches[1].Trim()] = $true }
    }
}

$header = @(
    '# Boundry secrets — outside MSSP repo (loaded by launch-boundry-ai.bat)',
    '# Generated by tools/migrate_secrets_to_boundry_home.ps1',
    ''
)
$newLines = New-Object System.Collections.Generic.List[string]
if (-not (Test-Path $dest)) {
    foreach ($h in $header) { [void]$newLines.Add($h) }
} else {
    foreach ($line in (Get-Content $dest -Encoding UTF8)) { [void]$newLines.Add($line) }
}

Get-Content $src -Encoding UTF8 | ForEach-Object {
    $line = $_.Trim()
    if (-not $line -or $line.StartsWith('#')) { return }
    if ($line -notmatch '^([^=]+)=(.*)$') { return }
    $key = $matches[1].Trim()
    if ($existing.ContainsKey($key)) { return }
    [void]$newLines.Add($line)
    $existing[$key] = $true
}

$newLines | Set-Content -Path $dest -Encoding UTF8
Write-Host "Merged into $dest (keys added from .env if missing)."
Write-Host 'Next: remove secret keys from C:\Dev\MSSP\.env or leave only non-secret flags.'
